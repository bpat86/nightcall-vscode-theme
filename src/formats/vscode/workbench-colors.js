const chroma = require("chroma-js");

function alpha(value, percentage) {
  if (!Number.isFinite(percentage) || percentage < 0 || percentage > 100) {
    throw new RangeError("Alpha percentage must be between 0 and 100");
  }

  return chroma(value)
    .alpha(percentage / 100)
    .hex();
}

